    // ---- velocity blackboard round-trip across 2 generations, hand-traced ----

    #[test]
    fn velocity_state_round_trips_and_accumulates_across_two_generations() {
        // n=2, dim=1, same fixture shape as the force-sanity test above.
        // Generation 0: v_old=[0,0] (bootstrap) -> gen0's v is EXACTLY the
        // gen0 acceleration (r1*0 + accel = accel, for ANY r1). Generation
        // 1: v_old is gen0's PERSISTED (nonzero, for agent 0 at least)
        // velocity -- gen1's v genuinely depends on it (r1_gen1 * v_gen0 +
        // accel_gen1), a real accumulation, not a reset.
        let dim = 1;
        let p = SphereShifted::new(vec![0.0; dim], -1000.0, 1000.0);
        let space = p.space();
        let mut evaluator = Evaluator::new(&p, 100_000);
        let mut rng = RngStream::from_master(3, &[]);
        let mut bb = Blackboard::new();

        let mut pop = Population {
            individuals: vec![g(vec![0.0]), g(vec![5.0])],
            fitness: vec![10.0, 1.0],
        };

        // Generation 0.
        let rng_before_gen0 = rng.clone();
        let mut ctx = Ctx { space, rng: &mut rng, eval: &mut evaluator, bb: &mut bb, iteration: 0 };
        let off0 = GsaGenerator.generate(&pop, &mut ctx);
        let velocity_after_gen0 = ctx.bb.get::<Vec<Vec<f64>>>("gsa/velocity").unwrap().clone();

        // Hand-trace generation 0 (mass, order, g, kbest are identical to
        // the force-sanity test above: M=[0.0,1.0], order=[1,0], kbest=2,
        // G=gsa_g(0.0)=100.0).
        let mut twin = rng_before_gen0;
        let rand0_gen0 = twin.next_f64(); // Gfield i=0 (j=1)
        let rand1_gen0 = twin.next_f64(); // Gfield i=1 (j=0)
        let g0 = gsa_g(0.0);
        let accel0_gen0 = g0 * gsa_force_term(rand0_gen0, 1.0, 5.0, 0.0, 5.0);
        let accel1_gen0 = g0 * gsa_force_term(rand1_gen0, 0.0, 0.0, 5.0, 5.0);
        assert_eq!(accel1_gen0, 0.0);
        let r1_move_0_gen0 = twin.next_f64();
        let r1_move_1_gen0 = twin.next_f64();
        let v0_gen0 = gsa_velocity_step(0.0, accel0_gen0, r1_move_0_gen0);
        let v1_gen0 = gsa_velocity_step(0.0, accel1_gen0, r1_move_1_gen0);
        assert_eq!(v1_gen0, 0.0, "v_old=0 * anything + accel(0.0) = 0.0 exactly");

        assert_eq!(velocity_after_gen0, vec![vec![v0_gen0], vec![v1_gen0]],
            "velocity after generation 0 must be exactly (r1*0 + accel) per agent");
        assert_eq!(floats(&off0[0])[0], 0.0 + v0_gen0);
        assert_eq!(floats(&off0[1])[0], 5.0 + v1_gen0);

        // replace/generational (hand-applied): pop <- off0, with made-up
        // fresh fitness (bat 1 still best) to drive generation 1's masses.
        pop.individuals = off0;
        pop.fitness = vec![7.0, 0.5];

        // Generation 1: velocity must be READ BACK (not re-bootstrapped)
        // and used as v_old in gsa_velocity_step -- genuinely different
        // from a fresh-zero run since v0_gen0 != 0.0 (overwhelmingly, since
        // rand0_gen0 is continuous).
        assert_ne!(v0_gen0, 0.0, "sanity: agent 0's gen-0 velocity must be nonzero for this test to be meaningful");
        let rng_before_gen1 = rng.clone();
        let mut ctx = Ctx { space, rng: &mut rng, eval: &mut evaluator, bb: &mut bb, iteration: 1 };
        let off1 = GsaGenerator.generate(&pop, &mut ctx);
        let velocity_after_gen1 = ctx.bb.get::<Vec<Vec<f64>>>("gsa/velocity").unwrap().clone();

        // Re-derive generation 1's mass/order/G/kbest from the NEW fitness
        // [7.0, 0.5] (agent 1, x=off0[1], still best) and NEW positions
        // (off0[0], off0[1]).
        let x1_0 = floats(&pop.individuals[0])[0];
        let x1_1 = floats(&pop.individuals[1])[0];
        // mass: Fmax=7.0, Fmin=0.5, best=0.5, worst=7.0.
        // raw m0=(7.0-7.0)/(0.5-7.0)=0.0; raw m1=(0.5-7.0)/(0.5-7.0)=1.0. sum=1.0.
        let mut twin1 = rng_before_gen1;
        let rand0_gen1 = twin1.next_f64();
        let rand1_gen1 = twin1.next_f64();
        let g1_val = gsa_g(0.0); // progress still 0 (this fresh Evaluator's used() is untouched by hand tracing)
        let r_dist1 = (x1_1 - x1_0).abs();
        let accel0_gen1 = g1_val * gsa_force_term(rand0_gen1, 1.0, x1_1, x1_0, r_dist1);
        let accel1_gen1 = g1_val * gsa_force_term(rand1_gen1, 0.0, x1_0, x1_1, r_dist1);
        assert_eq!(accel1_gen1, 0.0);
        let r1_move_0_gen1 = twin1.next_f64();
        let r1_move_1_gen1 = twin1.next_f64();
        // MUST use v0_gen0 as v_old (accumulated), not reset to 0.
        let v0_gen1 = gsa_velocity_step(v0_gen0, accel0_gen1, r1_move_0_gen1);
        let v1_gen1 = gsa_velocity_step(v1_gen0, accel1_gen1, r1_move_1_gen1);

        assert_eq!(velocity_after_gen1, vec![vec![v0_gen1], vec![v1_gen1]],
            "generation 1's velocity must ACCUMULATE on top of generation 0's persisted state");
        assert_eq!(floats(&off1[0])[0], x1_0 + v0_gen1);
        assert_eq!(floats(&off1[1])[0], x1_1 + v1_gen1);
        assert_ne!(velocity_after_gen1[0][0], v0_gen0,
            "sanity: velocity must actually have changed across the two generations (not silently frozen)");
    }
