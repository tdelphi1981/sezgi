    // ---- GsaGenerator: force antisymmetry-ish sanity, 2-agent 1-D, full arithmetic ----

    #[test]
    fn zero_mass_agent_exerts_zero_force_and_does_not_move_the_better_agent() {
        // n=2, dim=1. agent 0: x=0.0, fitness=10.0 (worse). agent 1: x=5.0,
        // fitness=1.0 (better). Mass: Fmax=10, Fmin=1, best=1, worst=10 ->
        // raw m0=(10-10)/(1-10)=0/-9=0.0; raw m1=(1-10)/(1-10)=1.0. sum=1.0
        // exactly (no floating error) -> M0=0.0, M1=1.0 EXACTLY.
        //
        // ds = order by mass descending = [1, 0]. progress=0 (fresh
        // evaluator, used=0) -> kbest_percent=100 -> kbest_count=2 (both).
        //
        // Force on agent 0 (i=0): ii=0 -> j=ds[0]=1 != 0 -> R=|0-5|=5.0,
        //   1 draw (dim=1): force0 = rand0 * M[1] * (5.0-0.0)/(5.0+eps)
        //                          = rand0 * 1.0 * 5.0/(5.0+eps).
        //   ii=1 -> j=ds[1]=0 == 0 -> SKIPPED (no draw).
        // Force on agent 1 (i=1): ii=0 -> j=ds[0]=1 == 1 -> SKIPPED.
        //   ii=1 -> j=ds[1]=0 != 1 -> R=|5-0|=5.0, 1 draw (dim=1):
        //     force1 = rand1 * M[0] * (0.0-5.0)/(5.0+eps) = rand1 * 0.0 * (...) = 0.0
        //     EXACTLY, regardless of rand1's value, because M[0]=0.0 kills the term.
        // accel1 = G * 0.0 = 0.0 exactly.
        //
        // move.m (separate loop, after Gfield fully completes): velocity
        // bootstraps to [[0.0],[0.0]]. v1_new = r1_move_1*0.0 + 0.0 = 0.0
        // exactly -> x1_new = 5.0 + 0.0 = 5.0 EXACTLY: the heavier/better
        // agent does not move this generation, regardless of ANY random draw.
        let dim = 1;
        let p = SphereShifted::new(vec![0.0; dim], -1000.0, 1000.0);
        let space = p.space();
        let mut evaluator = Evaluator::new(&p, 100_000);
        let mut rng = RngStream::from_master(11, &[]);
        let mut bb = Blackboard::new();
        let pop = Population {
            individuals: vec![g(vec![0.0]), g(vec![5.0])],
            fitness: vec![10.0, 1.0],
        };

        let mut ctx = Ctx { space, rng: &mut rng, eval: &mut evaluator, bb: &mut bb, iteration: 0 };
        let off = GsaGenerator.generate(&pop, &mut ctx);

        assert_eq!(floats(&off[1])[0], 5.0,
            "agent 1 (mass 1.0, only neighbor has mass 0.0) must not move at all this generation");
        // agent 0 DID move (accel0 is nonzero with overwhelming probability
        // -- rand0 is continuous on [0,1), so rand0==0 has probability 0).
        assert_ne!(floats(&off[0])[0], 0.0,
            "agent 0 (mass 0.0, pulled by agent 1's mass 1.0) must have moved");
    }

    #[test]
    fn zero_mass_agent_exact_displacement_matches_hand_traced_replay() {
        // Same 2-agent fixture as above, but replaying the EXACT draw
        // sequence via a twin stream to confirm agent 0's exact landing
        // position (full arithmetic, not just the sign/nonzero sanity
        // above). Draw order: Gfield's draws first (i=0's single draw,
        // since i=1's is skipped... wait: i=0 draws once (j=1), i=1 draws
        // once too (j=0) -- both agents DO consume exactly one draw each in
        // Gfield, it is only agent 1's CONTRIBUTION that is exactly zero
        // (multiplied by M[0]=0.0), not the draw itself. THEN move's draws
        // (one per agent, dim=1).
        let dim = 1;
        let p = SphereShifted::new(vec![0.0; dim], -1000.0, 1000.0);
        let space = p.space();
        let mut evaluator = Evaluator::new(&p, 100_000);
        let mut rng = RngStream::from_master(11, &[]);
        let rng_before = rng.clone();
        let mut bb = Blackboard::new();
        let pop = Population {
            individuals: vec![g(vec![0.0]), g(vec![5.0])],
            fitness: vec![10.0, 1.0],
        };

        let mut ctx = Ctx { space, rng: &mut rng, eval: &mut evaluator, bb: &mut bb, iteration: 0 };
        let off = GsaGenerator.generate(&pop, &mut ctx);

        let mut twin = rng_before;
        // Gfield: i=0 (j=1 != 0) draws rand0; i=1 (j=0 != 1) draws rand1.
        let rand0 = twin.next_f64();
        let _rand1 = twin.next_f64();
        let g0 = gsa_g(0.0);
        let force0 = gsa_force_term(rand0, 1.0, 5.0, 0.0, 5.0);
        let accel0 = g0 * force0;
        // move: i=0 draws r1_move_0 first, then i=1 draws r1_move_1.
        let r1_move_0 = twin.next_f64();
        let v0_new = gsa_velocity_step(0.0, accel0, r1_move_0);
        let x0_new = 0.0 + v0_new;

        assert_eq!(floats(&off[0])[0], x0_new,
            "agent 0's exact landing position must match the hand-traced replay");
    }

    // ---- twin-stream draw count, crafted (n, dim), progress=0 (kbest=n) ----

    #[test]
    fn draw_count_at_progress_zero_is_n_squared_times_dim() {
        // At progress=0, kbest_count == n (ALL agents), so for every target
        // agent i, exactly one of the n slots in `order` equals i (skipped,
        // no draw) and the other (n-1) each consume `dim` draws in Gfield --
        // n*(n-1)*dim total, REGARDLESS of the mass ranking (order is just
        // some permutation of 0..n). Then move.m consumes n*dim more draws.
        // Total = n*(n-1)*dim + n*dim = n^2*dim.
        let n = 5; let dim = 3;
        let p = SphereShifted::new(vec![0.0; dim], -5.0, 5.0);
        let space = p.space();
        let pop = pop_nd(n, dim);

        let mut rng = RngStream::from_master(7, &[]);
        let rng_before = rng.clone();
        let mut evaluator = Evaluator::new(&p, 1000); // fresh: used()=0 -> progress=0
        let mut bb = Blackboard::new();
        {
            let mut ctx = Ctx { space, rng: &mut rng, eval: &mut evaluator, bb: &mut bb, iteration: 0 };
            let off = GsaGenerator.generate(&pop, &mut ctx);
            assert_eq!(off.len(), n);
        }

        let expected_draws = n * n * dim;
        let mut twin = rng_before;
        for _ in 0..expected_draws { twin.next_f64(); }
        assert_eq!(rng.next_f64(), twin.next_f64(),
            "gen/gsa at progress=0 must consume exactly n^2*dim draws (n={n}, dim={dim}): n*(n-1)*dim in Gfield + n*dim in move");
    }

